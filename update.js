write('bridge/blender_bridge.py', [
  "import bpy, socket, threading, json, queue, traceback, time, sys, os",
  "",
  "PORT = int(os.environ.get('OMNIBLEND_PORT', 9876))",
  "",
  "q = queue.Queue()",
  "",
  "def ensure_context():",
  "    try:",
  "        if bpy.context.scene and len(bpy.context.scene.objects) > 0:",
  "            if not bpy.context.view_layer.objects.active:",
  "                bpy.context.view_layer.objects.active = bpy.context.scene.objects[0]",
  "                bpy.context.scene.objects[0].select_set(True)",
  "    except: pass",
  "",
  "def take_snapshot():",
  "    s = bpy.context.scene",
  "    return {'scene':{'name':s.name,'objects':[{'name':o.name,'type':o.type,'location':list(o.location),'dimensions':list(o.dimensions),'materials':[m.name for m in (o.data.materials if hasattr(o.data,'materials') else []) if m]} for o in s.objects],'render':{'engine':s.render.engine}}}",
  "",
  "def handle(msg):",
  "    op = msg.get('op')",
  "    if op == 'ping':",
  "        return {'ok': True, 'version': bpy.app.version_string}",
  "    if op == 'exec':",
  "        ensure_context()",
  "        ns = {'bpy': bpy, '__name__': '__omniblend__'}",
  "        try:",
  "            exec(msg.get('code', ''), ns)",
  "            return {'ok': True, 'output': ''}",
  "        except Exception:",
  "            return {'ok': False, 'error': traceback.format_exc()}",
  "    if op == 'snapshot':",
  "        return {'ok': True, 'snapshot': take_snapshot()}",
  "    return {'ok': False, 'error': 'unknown op'}",
  "",
  "def process_queue():",
  "    try:",
  "        while True:",
  "            msg, conn = q.get_nowait()",
  "            try:",
  "                result = handle(msg)",
  "                conn.sendall((json.dumps({'id': msg['id'], 'result': result}) + '\\n').encode())",
  "            except Exception as e:",
  "                print('Error:', e, flush=True)",
  "    except queue.Empty:",
  "        pass",
  "    return 0.05",
  "",
  "def client_loop(conn):",
  "    buf = b''",
  "    try:",
  "        while True:",
  "            data = conn.recv(65536)",
  "            if not data: break",
  "            buf += data",
  "            while b'\\n' in buf:",
  "                line, buf = buf.split(b'\\n', 1)",
  "                try: msg = json.loads(line.decode())",
  "                except: continue",
  "                q.put((msg, conn))",
  "    except Exception: pass",
  "    finally:",
  "        try: conn.close()",
  "        except: pass",
  "",
  "def accept_loop(srv):",
  "    while True:",
  "        try:",
  "            conn, _ = srv.accept()",
  "        except OSError: break",
  "        threading.Thread(target=client_loop, args=(conn,), daemon=True).start()",
  "",
  "srv = socket.socket(socket.AF_INET, socket.SOCK_STREAM)",
  "srv.setsockopt(socket.SOL_SOCKET, socket.SO_REUSEADDR, 1)",
  "try:",
  "    srv.bind(('127.0.0.1', PORT))",
  "except OSError:",
  "    print(f'Port {PORT} in use.', flush=True)",
  "    sys.exit(1)",
  "srv.listen(4)",
  "threading.Thread(target=accept_loop, args=(srv,), daemon=True).start()",
  "bpy.app.timers.register(process_queue, first_interval=0.1)",
  "print('[bridge] listening on', PORT, flush=True)"
].join('\n'));

